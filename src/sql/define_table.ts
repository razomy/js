export type DataType =
  // Строковые
  | 'String' // VARCHAR(length)
  | 'Char' // CHAR(length) - фиксированная длина (для ISO кодов: RU, USD)
  | 'Text' // TEXT - безлимитная строка
  // Числовые
  | 'SmallInt' // SMALLINT (2 bytes, -32768 to +32767) - для кодов HTTP, возрастов
  | 'Int' // INTEGER (4 bytes)
  | 'BigInt' // BIGINT (8 bytes) - для больших ID и счетчиков
  | 'Decimal' // NUMERIC(precision, scale) - для денег и точных наук
  | 'Float' // REAL (4 bytes)
  | 'Double' // DOUBLE PRECISION (8 bytes) - для координат
  // Логические
  | 'Bool' // BOOLEAN
  // Дата и время
  | 'Date' // DATE (YYYY-MM-DD)
  | 'Time' // TIME (HH:MM:SS)
  | 'Timestamp' // TIMESTAMP WITHOUT TIME ZONE
  | 'Timestamptz' // TIMESTAMP WITH TIME ZONE (Рекомендуется для Postgres!)
  // Специфичные для PostgreSQL
  | 'Uuid' // UUID
  | 'Jsonb' // JSONB (бинарный JSON с поддержкой индексов)
  | 'Bytea' // BYTEA (бинарные данные / файлы)
  | 'Inet'; // INET (IPv4 / IPv6 адреса)

export interface ColumnConfig {
  type: DataType;
  /** Для String / Char */
  length?: number;
  /** Общее количество знаков для Decimal (например, 10) */
  precision?: number | undefined;
  /** Количество знаков после запятой для Decimal (например, 2) */
  scale?: number | undefined;
  /** В PostgreSQL любой тип можно сделать нативным массивом (например, TEXT[] или VARCHAR(64)[]) */
  isArray?: boolean | undefined;
  nullable?: boolean;
  /** Дефолтное значение (или спец. слова вроде 'now()', 'gen_random_uuid()') */
  default_?: string | boolean | number | Record<string, unknown> | unknown[];
  /** Ограничение UNIQUE на уровне одной колонки */
  unique?: boolean | undefined;
  /** Автоинкремент (GENERATED BY DEFAULT AS IDENTITY в современном PG) */
  autoIncrement?: boolean | undefined;
  /** Внешний ключ (Foreign Key) */
  references?:
    | {
        table: string;
        column: string;
        onDelete?: 'CASCADE' | 'SET NULL' | 'RESTRICT' | 'NO ACTION';
      }
    | undefined;
  /** Из какого старого поля скопировать данные (при переименовании или разделении) */
  migrateFrom?: string;
  /** Кастомное SQL-выражение при переносе, например: " LOWER(old_col) " */
  transformSql?: string;
}

export type FieldDef = DataType | ColumnConfig;

export interface TableDeclaration<R extends Record<string, FieldDef> = Record<string, FieldDef>> {
  title: string;
  name_: string;
  description: string;
  record: R;
  primary?: Partial<Record<keyof R, boolean>>;
  index?: Partial<Record<keyof R, boolean>>;
  /** Составные уникальные ключи (например, [ ['country', 'city'] ]) */
  uniqueTogether?: (keyof R)[][];
  migrationRules?: {
    droppedColumns?: string[];
    ignoreColumns?: string[];
  };
}

export function defineTable<R extends Record<string, FieldDef>>(table: TableDeclaration<R>): TableDeclaration<R> {
  return table;
}

